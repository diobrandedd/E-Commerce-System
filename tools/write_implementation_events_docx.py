#!/usr/bin/env python3
"""Generate a Word briefing of recent Pyx Tracker code implementations."""

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "_System_Core" / "docs" / "2026-08-19_implemented-events.docx"

GOLD = RGBColor(0xC8, 0x90, 0x0A)
BROWN = RGBColor(0x3B, 0x2A, 0x00)
MUTED = RGBColor(0x5C, 0x4A, 0x2A)


def set_run(run, *, size=11, bold=False, color=None, italic=False):
    run.font.name = "Calibri"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color


def add_heading_styled(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.color.rgb = BROWN if level == 1 else GOLD
        run.font.name = "Calibri"
    return p


def add_body(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run(run, size=11, color=BROWN)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.line_spacing = 1.15
    return p


def add_bullet(doc, text, bold_lead=None):
    p = doc.add_paragraph(style="List Bullet")
    if bold_lead:
        r0 = p.add_run(bold_lead)
        set_run(r0, size=11, bold=True, color=BROWN)
        r1 = p.add_run(text)
        set_run(r1, size=11, color=BROWN)
    else:
        r = p.add_run(text)
        set_run(r, size=11, color=BROWN)
    p.paragraph_format.space_after = Pt(4)
    return p


def shade_header_row(row):
    for cell in row.cells:
        tc = cell._tc
        tcPr = tc.get_or_add_tcPr()
        shd = tcPr.makeelement(
            qn("w:shd"),
            {
                qn("w:val"): "clear",
                qn("w:color"): "auto",
                qn("w:fill"): "F4E6C4",
            },
        )
        tcPr.append(shd)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    hdr = table.rows[0]
    for i, h in enumerate(headers):
        cell = hdr.cells[i]
        cell.text = ""
        p = cell.paragraphs[0]
        run = p.add_run(h)
        set_run(run, size=10, bold=True, color=BROWN)
    shade_header_row(hdr)
    for r_i, row in enumerate(rows):
        for c_i, val in enumerate(row):
            cell = table.rows[r_i + 1].cells[c_i]
            cell.text = ""
            p = cell.paragraphs[0]
            run = p.add_run(val)
            set_run(run, size=10, color=BROWN)
    doc.add_paragraph()
    return table


def build():
    doc = Document()
    for section in doc.sections:
        section.top_margin = Inches(0.9)
        section.bottom_margin = Inches(0.9)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = title.add_run("Pyx Tracker")
    set_run(r, size=12, bold=True, color=GOLD)

    h = doc.add_paragraph()
    r = h.add_run("Implementation briefing")
    set_run(r, size=22, bold=True, color=BROWN)
    h.paragraph_format.space_after = Pt(2)

    sub = doc.add_paragraph()
    r = sub.add_run(
        "What was implemented in the application code (18–19 August 2026), "
        "and why these workflows belong in the system instead of Word, Excel, or other office tools."
    )
    set_run(r, size=11, italic=True, color=MUTED)
    sub.paragraph_format.space_after = Pt(12)

    meta = doc.add_paragraph()
    r = meta.add_run(
        "System: Pyx Tracker (inventory, walk-in POS, pack scan, sales).  "
        "This file was generated by a Python script (python-docx), not typed by hand in Microsoft Word."
    )
    set_run(r, size=10, color=MUTED)

    add_heading_styled(doc, "1. Purpose of this document", 1)
    add_body(
        doc,
        "This briefing lists the product events that were built into Pyx Tracker during this work cycle. "
        "An “event” here means a real operation on the floor (a sale, a discount, a pack scan, a barcode correction) "
        "that the software now records, enforces, and displays. The second half explains why those events were not "
        "left as a manual process in spreadsheets or Word forms.",
    )

    add_heading_styled(doc, "2. Events implemented in code", 1)

    add_heading_styled(doc, "2.1 Staff account opens Walk-in POS", 2)
    add_body(
        doc,
        "Cashiers no longer need a separate POS PIN screen on the login page. A staff account that is granted "
        "the Walk-in POS permission (pos.sell) sees POS in the sidebar. Executives already have every permission, "
        "so they see POS without a extra grant. After sign-in they work in the same Pyx Tracker session; Exit from "
        "POS returns them to the dashboard instead of logging them out.",
    )
    add_bullet(doc, "Permission catalog key pos.sell (Staff Management checkboxes).", bold_lead="Where: ")
    add_bullet(doc, "Route /pos, sidebar item, API session accepts an IMS user or a leftover PIN session.", bold_lead="Where: ")
    add_bullet(doc, "Database phase 65: pos_sales.sold_by_user_id stores which user completed the sale.", bold_lead="Where: ")

    add_heading_styled(doc, "2.2 Walk-in sale at full price or with 10% / 20% off", 2)
    add_body(
        doc,
        "At checkout the cashier enters the buyer name (optional credentials) and chooses Pay full price, 10% off, "
        "or 20% off. The sale completes immediately. The receipt stores the discount percent and amount. There is "
        "no waiting overlay and no executive “approve discount” queue for new sales. The person who pressed checkout "
        "is stored as the seller.",
    )
    add_bullet(doc, "Unified POS checkout writes pos_sales and pos_receipt_items, consumes scanned stickers.", bold_lead="What happens: ")
    add_bullet(doc, "Discount is a fact on the receipt, not a separate request ticket.", bold_lead="What happens: ")

    add_heading_styled(doc, "2.3 Walk-in sale appears on the Sales tab", 2)
    add_body(
        doc,
        "Every POS receipt lands on Sales → Recent walk-in sales. The list shows when it sold, receipt number, "
        "Sold by (staff name), Sold to (buyer), line items, whether it was regular / discounted / AR, and the total. "
        "Tapping All products or a product card (Honey, Paragis, Black Rice, Cacao, Honey Comb) filters receipts "
        "that contain at least one matching line.",
    )

    add_heading_styled(doc, "2.4 Login is account-only (PIN POS removed from the door)", 2)
    add_body(
        doc,
        "The login page no longer offers Walk-in POS (PIN). Everyone signs in with username and password. "
        "POS is reached from inside the app. That matches “POS lives on every account via the permission set.”",
    )

    add_heading_styled(doc, "2.5 Pack scan: product row expands to barcodes", 2)
    add_body(
        doc,
        "On Deliveries → Pack scan, the live session still shows how many of each product are in the parcel. "
        "Each product row is expandable. Opening it lists the exact barcodes (and batch) that were scanned for that product. "
        "History already showed codes when a past session is expanded; the live session now matches that idea without a second standalone table.",
    )

    add_heading_styled(doc, "2.6 Pack scan: remove one mistaken barcode", 2)
    add_body(
        doc,
        "If a sticker was scanned by mistake, the operator expands the product row and removes that barcode. "
        "The unit is not deducted from stock until Confirm. After remove, the same sticker can be scanned again. "
        "Confirmed history stays read-only — past packs are not edited from this screen.",
    )
    add_bullet(doc, "API action pack_remove_item; only draft sessions; deletes one honey or dept session line.", bold_lead="Where: ")

    add_heading_styled(doc, "3. Event map (user action → system record)", 1)
    add_table(
        doc,
        ["Floor event", "Recorded in the system as", "Visible to ops as"],
        [
            [
                "Staff signs in and opens POS",
                "IMS session + pos.sell check",
                "Sidebar POS; Exit → dashboard",
            ],
            [
                "Checkout full price / 10% / 20%",
                "pos_sales row (seller user id, discount, buyer)",
                "Printed receipt; Sales list Sold by / Sold to",
            ],
            [
                "Filter Sales by product",
                "Query on receipt lines (dept_product_key / honey)",
                "Recent walk-in sales list only",
            ],
            [
                "Scan a sticker into a pack session",
                "Draft pack session item (honey or dept)",
                "Product qty; expand row for barcode",
            ],
            [
                "Remove a barcode from the session",
                "DELETE of that draft line only",
                "Qty drops; sticker can be scanned again",
            ],
            [
                "Confirm pack scan",
                "Units marked packed; honey packaging / dept finished deducted",
                "History tab (read-only)",
            ],
        ],
    )

    add_heading_styled(doc, "4. Why this was built in code, not done manually in office tools", 1)
    add_body(
        doc,
        "Word, Excel, chat, and paper can describe a sale or a packed parcel. They cannot be the system of record "
        "for Pyx Tracker. These events were implemented in the PHP APIs and React screens for the following reasons.",
    )

    add_heading_styled(doc, "4.1 Stock must move with the event", 2)
    add_body(
        doc,
        "A walk-in sale consumes a specific bottle or pouch/jar sticker. A confirmed pack scan marks those units packed "
        "and deducts finished / packaging stock. If someone typed the same story into Excel, inventory would not change. "
        "If they changed Excel later, inventory would still be wrong. Code runs the deduct in the same transaction as the receipt.",
    )

    add_heading_styled(doc, "4.2 Who did it must be the logged-in person", 2)
    add_body(
        doc,
        "A spreadsheet “sold by” column is whatever someone types. The POS seller is taken from the signed-in user "
        "(or, historically, a PIN terminal). Pack scan remove and confirm use the same staff session. That is why "
        "Sales can show Sold by without a second manual log.",
    )

    add_heading_styled(doc, "4.3 Permissions cannot live in a shared workbook", 2)
    add_body(
        doc,
        "Walk-in POS is a checkbox on the staff account. Executives see everything; other roles only see POS if granted. "
        "A Word SOP that says “only cashiers use POS” does not stop someone opening a shared Excel POS sheet. "
        "The route and API refuse the action unless pos.sell (or an executive) is present.",
    )

    add_heading_styled(doc, "4.4 Discounts must match the receipt, not a side list", 2)
    add_body(
        doc,
        "The old flow asked for executive approval in a request queue. That was easy to miss (and staff accounts could not "
        "even open POS). Putting 10% / 20% on checkout writes discount_percent on the same sale the customer paid. "
        "A separate Word “discount log” would drift from receipts and from Sales filters.",
    )

    add_heading_styled(doc, "4.5 Barcodes are unique units, not a typed count", 2)
    add_body(
        doc,
        "Typing “3 × Amber 1L” in Excel does not prove which three stickers left the shelf. Pack scan stores each code. "
        "Expanding the row is how the operator checks the actual labels. Removing one code is a draft correction; "
        "it is not rewriting history after Confirm. Office tools have no notion of draft vs confirmed pack sessions.",
    )

    add_heading_styled(doc, "4.6 Duplicate and already-sold stickers need an immediate answer", 2)
    add_body(
        doc,
        "The scanner already rejects duplicates in the session and units that were packed or sold earlier. "
        "A manual checklist cannot query the barcode tables in real time. That check only exists in the scan API.",
    )

    add_heading_styled(doc, "4.7 One source of truth for later reports", 2)
    add_body(
        doc,
        "Sales filters, pack history, and inventory all read the same tables. If ops kept a parallel Word/Excel trail, "
        "every report would need a human merge. Building the event in code means the Sales tab and Pack scan History "
        "are views of the same facts, not a second set of numbers.",
    )

    add_heading_styled(doc, "5. What is still not a “tool” substitute", 1)
    add_body(
        doc,
        "Granting Walk-in POS to each non-executive is still a Staff Management action (not auto-granted to every old account). "
        "Production databases besides this machine still need the phase 65 SQL if account POS checkout has not been migrated. "
        "Hard-refresh the SPA after deploy so browsers load the new screens. Those are operational steps around the code; "
        "they are not replacements for the events above.",
    )

    add_heading_styled(doc, "6. Files touched (for IT / next developer)", 1)
    add_table(
        doc,
        ["Area", "Main files"],
        [
            [
                "POS permission and checkout seller",
                "includes/permissions.php, includes/pos_unified.php, api/v1/pos.php, Sidebar, routes, POSUnifiedPage",
            ],
            [
                "Sales list seller / buyer / product filter",
                "includes/honey_sales_report.php, api/v1/sales.php, SalesPage.tsx",
            ],
            [
                "Seller column on receipts",
                "sql/migration_phase65_pos_sold_by_user.sql",
            ],
            [
                "Login without PIN POS",
                "app/src/app/pages/LoginPage.tsx",
            ],
            [
                "Pack scan expand + remove barcode",
                "includes/honey_bottle_barcodes.php, api/v1/bottle_barcodes.php, HoneyPackScanPage.tsx",
            ],
        ],
    )

    add_heading_styled(doc, "7. How this Word file was produced", 1)
    add_body(
        doc,
        "This .docx was written by tools/write_implementation_events_docx.py using the python-docx library. "
        "That is only how the briefing file was created. The operations themselves (sales, discounts, pack scans) "
        "were implemented in the Pyx Tracker application so they run for every cashier and packer, not only in a document.",
    )

    footer = doc.add_paragraph()
    r = footer.add_run("Pyx Tracker  ·  Internal briefing  ·  19 August 2026")
    set_run(r, size=9, italic=True, color=MUTED)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    build()
